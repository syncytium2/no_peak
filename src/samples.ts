/**
 * Every digitized note has to name its source itself.
 *
 * The app shows one note at a time, folded into an "about this dataset"
 * accordion, so a note reading "Fig. 4A of the same paper" is orphaned the
 * moment anyone opens it — there is no preceding note on screen for "the same"
 * to refer to. Four of these were written that way and read as incomplete.
 * Lead with the reference, every time, however repetitive it looks in source.
 */
const MEASURED_ = "MEASURED. Webster et al. 1991 (Endocrinology 129:1635)";

/**
 * Identical on all eight digitized records, so it lives once rather than eight
 * times. This paragraph is the one that must never drift between them: the
 * error column drives detection on these files, and every record has to say
 * that it is an assumption rather than a measurement.
 */
const RECON_ERR =
  " Its error column is reconstructed, not read off the page: the figure has no error " +
  "bars and the paper does not say what error it gave CLUSTER, so the file supplies " +
  "max(floor, 8% of value) — the floor being the assay sensitivity the paper reports " +
  "for LH, and a value fitted to that paper's own pulse calls for GnRH. Detection needs " +
  "it: at one-point windows the estimated models let a pulse inflate its own error and " +
  "hide itself.";

export interface Sample {
  key: string;
  /** Group heading in the picker. */
  group: string;
  /** Short human label; the point count is appended at render time. */
  label: string;
  /**
   * Where the numbers came from. "simulated" is generated and resembles no
   * animal; "digitized" was read off a published figure and is a real record,
   * carrying the figure's line width as error. The two must never be confused,
   * so the tag is on the dataset rather than left to the note.
   */
  provenance: "simulated" | "digitized";
  /** What it is meant to resemble, and on what evidence. */
  note: string;
  /** Units of the sample times. */
  timeUnit: TimeUnit;
  /** Sampling interval, for the files that carry no time column. */
  deltaT: number;
  /** Units of the measured values, for the y-axis label. */
  valueLabel: string;
  /**
   * One line naming where the numbers came from, carried into every export.
   * A figure or results table that leaves this app must say whose data it is
   * and that it was read off a printed page, so that a reader who meets the
   * numbers downstream can tell what they are without coming back here.
   */
  citation?: string;
  load: () => ParsedSeries;
}

