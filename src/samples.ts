// Sample datasets bundled with the app, of two kinds that must never be
// confused — hence `provenance` on every entry.
//
// DIGITIZED: real records, read off the published figures of Webster et al.
// 1991. The figures mark every pulse that paper's own CLUSTER run identified,
// so these carry a ground truth this project did not produce. They are
// approximate to the width of a printed line. The article is not redistributed
// — only these numbers, which are measurements.
// See data/digitized/README.md and tools/digitize_webster1991.py, and
// docs/figure-data-permissions.md for the rights position, its limits, and why
// no claim of an author's permission appears anywhere here.
//
// SIMULATED: generated by tools/make_synthetic.py from a seeded PRNG. They match
// no animal and no experiment, but their scales — sampling interval, baseline,
// pulse amplitude, pulse frequency, assay CV — are taken from the published
// literature rather than invented. See data/synthetic/README.md for the sources
// and the standard any test data added here has to meet.
//
// Every dataset carries its own sampling interval and time unit, so a figure is
// never plotted on a fictitious axis.

